"""Generate only the canonical vocabularies consumed by browser scenes."""

from __future__ import annotations

import argparse
import json
from enum import StrEnum
from pathlib import Path

from archkeel.ir.architecture_graph import (
    AssessmentChange,
    AssessmentStatus,
    ComponentRole,
    EntityKind,
    GraphSchemaVersion,
    ModifierKind,
    OriginKind,
    ParameterKind,
    PresenceKind,
    RelationshipKind,
    ResolutionKind,
    VisibilityKind,
)
from archkeel.render.atlas_deviations import AtlasDeviationKind

_DOMAINS: tuple[type[StrEnum], ...] = (
    AtlasDeviationKind,
    OriginKind,
    EntityKind,
    RelationshipKind,
    PresenceKind,
    ResolutionKind,
    VisibilityKind,
    ParameterKind,
    ModifierKind,
    ComponentRole,
    AssessmentStatus,
    AssessmentChange,
    GraphSchemaVersion,
)
_OUTPUT = Path(__file__).parents[1] / "src/archkeel/render/assets/report-graph-vocabulary.ts"


def vocabulary_source() -> str:
    lines = [
        "// Generated by tools/browser_graph_protocol.py from canonical Python Enums.",
        "// Do not maintain wire spellings here.",
        "namespace ArchkeelGraphProtocol {",
    ]
    for domain in _DOMAINS:
        name = domain.__name__
        mapping = name[0].lower() + name[1:] + "Values"
        lines.append(f"  // {domain.__module__}.{name}")
        lines.append(f"  export enum {name} {{")
        lines.extend(f"    {entry.name} = {json.dumps(entry.value)}," for entry in domain)
        lines.extend(
            [
                "  }",
                f"  const {mapping}: ReadonlyMap<unknown, {name}> = new Map(",
                f"    Object.values({name}).map((value): [unknown, {name}] => [value, value]),",
                "  );",
                f"  export function is{name}(value: unknown): value is {name} {{",
                f"    return {mapping}.has(value);",
                "  }",
            ]
        )
    return "\n".join([*lines, "}", ""])


class _Arguments(argparse.Namespace):
    check: bool = False


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    arguments = parser.parse_args(namespace=_Arguments())
    source = vocabulary_source().encode("utf-8")
    if arguments.check:
        if _OUTPUT.read_bytes() != source:
            raise SystemExit("Browser graph vocabulary is stale")
    else:
        _OUTPUT.write_bytes(source)


if __name__ == "__main__":
    main()
