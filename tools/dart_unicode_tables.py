"""Write the Unicode tables of the native Dart collector from the oracle Python 3.11 (L-27).

The Python Dart collector uses `re` and `str` predicates whose Unicode data depends on the
interpreter. The oracle is Python 3.11 with Unicode 14.0.0 (AD-369). This script asks that
interpreter for each code point and writes `native/dart/src/unicode_tables.rs`:

- `WORD`: `re.match(r"\\w", chr(c))` for a `str` pattern.
- `SPACE`: `chr(c).isspace()`, which `re` `\\s`, `str.strip` and `str.split` use. The script
  checks that `\\s` and `isspace` agree on each code point.
- `LINE_BREAK`: the code points where `str.splitlines` breaks.
- `ASSIGNED`: `unicodedata.category(chr(c)) != "Cn"`.
- `ALNUM`: `chr(c).isalnum()`, which `_canonical_range` reads for the first character of a token.
- `DECIMAL`: `chr(c).isdecimal()`, the digits of a Python SDK version component.
- `BYTE_WORD`, `BYTE_SPACE`, `BYTE_DIGIT`: `\\w`, `\\s` and `\\d` of a `bytes` pattern.

Each table is a sorted list of inclusive ranges. The surrogates (U+D800 to U+DFFF) are left out:
a Rust `char` cannot hold one. The file also holds the SHA-256 of each table, so a test sees a
hand edit.

Usage:
    uv run python tools/dart_unicode_tables.py          # write the file
    uv run python tools/dart_unicode_tables.py --check  # exit 1 when the file differs
"""

from __future__ import annotations

import argparse
import hashlib
import re
import sys
import unicodedata
from collections.abc import Callable, Iterable
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
TARGET = ROOT / "native" / "dart" / "src" / "unicode_tables.rs"
ORACLE = ((3, 11), "14.0.0")
SURROGATES = range(0xD800, 0xE000)
# The tables that the collector reads; the others only check a Rust predicate in a test.
RUNTIME = frozenset({"WORD", "SPACE", "ASSIGNED", "ALNUM", "DECIMAL"})


def code_points() -> Iterable[int]:
    return (c for c in range(0x110000) if c not in SURROGATES)


def ranges(selected: Iterable[int]) -> list[tuple[int, int]]:
    found: list[tuple[int, int]] = []
    for c in selected:
        if found and found[-1][1] == c - 1:
            found[-1] = (found[-1][0], c)
        else:
            found.append((c, c))
    return found


def breaks(c: int) -> bool:
    return len(("a" + chr(c) + "b").splitlines()) == 2


def tables() -> dict[str, list[tuple[int, int]]]:
    if (sys.version_info[:2], unicodedata.unidata_version) != ORACLE:
        raise SystemExit(f"the oracle is Python 3.11 with Unicode 14.0.0, not {sys.version}")
    mismatch = [c for c in code_points() if (re.match(r"\s", chr(c)) is None) == chr(c).isspace()]
    if mismatch:
        raise SystemExit(f"re \\s and str.isspace differ at {mismatch[:5]}")
    text: dict[str, Callable[[int], bool]] = {
        "WORD": lambda c: re.match(r"\w", chr(c)) is not None,
        "SPACE": lambda c: chr(c).isspace(),
        "LINE_BREAK": breaks,
        "ASSIGNED": lambda c: unicodedata.category(chr(c)) != "Cn",
        "ALNUM": lambda c: chr(c).isalnum(),
        "DECIMAL": lambda c: chr(c).isdecimal(),
    }
    raw: dict[str, Callable[[int], bool]] = {
        "BYTE_WORD": lambda b: re.match(rb"\w", bytes([b])) is not None,
        "BYTE_SPACE": lambda b: re.match(rb"\s", bytes([b])) is not None,
        "BYTE_DIGIT": lambda b: re.match(rb"\d", bytes([b])) is not None,
    }
    result = {name: ranges(c for c in code_points() if test(c)) for name, test in text.items()}
    result.update({name: ranges(b for b in range(256) if test(b)) for name, test in raw.items()})
    return result


def digest(found: list[tuple[int, int]]) -> str:
    return hashlib.sha256(repr(found).encode("ascii")).hexdigest()


def render(found: dict[str, list[tuple[int, int]]]) -> str:
    lines = [
        "// Archkeel",
        "// Copyright (c) 2026 Rapiddweller Asia Co., Ltd.",
        "// SPDX-License-Identifier: MIT",
        "",
        "//! Generated by `tools/dart_unicode_tables.py` from Python 3.11.12 with Unicode 14.0.0",
        "//! (L-27, AD-369). Do not edit: run the script. Each table is a text of inclusive code",
        "//! point ranges `START-END` in hex; `pytext::ranges` reads it. The SHA-256 is over the",
        "//! Python `repr` of the list of ranges.",
        "",
    ]
    for name, items in found.items():
        cells = [f"{start:04X}-{end:04X}" for start, end in items]
        rows = [" ".join(cells[i : i + 8]) for i in range(0, len(cells), 8)]
        lines.append(f"/// SHA-256 {digest(items)}, {len(items)} ranges.")
        if name not in RUNTIME:
            lines.append("#[cfg(test)]")
        lines.append(f'pub(crate) const {name}: &str = "\\')
        lines.extend(f"    {row} \\" for row in rows)
        lines.append('";')
        lines.append("")
    return "\n".join(lines)


def main(argv: list[str] | None = None) -> int:
    arguments = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    arguments.add_argument("--check", action="store_true", help="compare, do not write")
    options = arguments.parse_args(argv)
    text = render(tables())
    if options.check:
        current = TARGET.read_text(encoding="utf-8") if TARGET.exists() else ""
        if current != text:
            print(f"{TARGET.relative_to(ROOT)} differs from the oracle tables")
            return 1
        return 0
    TARGET.write_text(text, encoding="utf-8")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
