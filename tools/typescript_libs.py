"""Generate the TypeScript standard-library catalog from the pinned compiler's lib files.

The compiler's lib table names the values a `lib` option accepts, and each name is one
`lib.*.d.ts` file. A file's top-level value declarations are the globals it proves, and its
`/// <reference lib>` lines are its dependencies. `--check` fails when the checked-in module
differs from what the pinned compiler produces; `--write` (the default) regenerates it.
"""

from __future__ import annotations

import argparse
import json
import re
import subprocess
import sys
from pathlib import Path
from typing import Final

from archkeel.analyzer.typescript.config import ScriptTarget

ROOT: Final = Path(__file__).resolve().parents[1]
TYPESCRIPT: Final = ROOT / "tools/browser-runtime/node_modules/typescript"
OUTPUT: Final = ROOT / "src/archkeel/analyzer/typescript/standard_libs.py"

_LIB_TABLE: Final = re.compile(r"var libEntries = \[(.*?)\];", re.DOTALL)
_TARGET_TABLE: Final = re.compile(r"var targetToLibMap = .*?new Map\(\[(.*?)\]\);", re.DOTALL)
_LIB_ENTRY: Final = re.compile(r'\["([a-z0-9.]+)", "(lib\.[a-z0-9.]+\.d\.ts)"\]')
_TARGET_ENTRY: Final = re.compile(r'\[\d+ /\* (\w+) \*/, "(lib\.[a-z0-9.]+\.d\.ts)"\]')
_GLOBAL: Final = re.compile(
    r"^declare (?:abstract )?(?:var|function|class|namespace|const|let) ([A-Za-z0-9_$]+)",
    re.MULTILINE,
)
_REFERENCE: Final = re.compile(r'^/// <reference lib="([a-z0-9.]+)" />', re.MULTILINE)
# The compiler gives ES6 the same value as ES2015, so both targets share one default file.
_TARGET_ALIAS: Final = {"es6": "es2015"}
# getDefaultLibFileName's default branch: ES3 and ES5 (and no target at all).
_ES5_DEFAULT_FILE: Final = "lib.d.ts"


def _table(pattern: re.Pattern[str], text: str, what: str) -> str:
    found = pattern.search(text)
    if found is None:
        raise SystemExit(f"typescript_libs: could not find the compiler's {what} table")
    return found.group(1)


def _member(name: str) -> str:
    return name.upper().replace(".", "_")


def _read(file_name: str) -> tuple[frozenset[str], tuple[str, ...]]:
    text = (TYPESCRIPT / "lib" / file_name).read_text(encoding="utf-8")
    return frozenset(_GLOBAL.findall(text)), tuple(_REFERENCE.findall(text))


def _literal(names: frozenset[str] | tuple[str, ...]) -> str:
    items = ", ".join(f"StandardLibrary.{_member(name)}" for name in names)
    return f"({items},)" if items else "()"


def build_module() -> str:
    text = (TYPESCRIPT / "lib" / "typescript.js").read_text(encoding="utf-8")
    version = json.loads((TYPESCRIPT / "package.json").read_text(encoding="utf-8"))["version"]
    # A Map keeps the last entry for a repeated name, as the compiler does.
    files: dict[str, str] = dict(_LIB_ENTRY.findall(_table(_LIB_TABLE, text, "lib")))
    default_files: dict[str, str] = {
        name.upper(): file
        for name, file in _TARGET_ENTRY.findall(_table(_TARGET_TABLE, text, "default lib"))
    }
    for name, file in files.items():
        if not (TYPESCRIPT / "lib" / file).is_file():
            raise SystemExit(f"typescript_libs: {name} names a missing file {file}")
    catalog = {name: _read(file) for name, file in files.items()}
    for name, (_, references) in catalog.items():
        unknown = sorted(set(references) - set(files))
        if unknown:
            raise SystemExit(f"typescript_libs: {name} references unknown libs {unknown}")

    defaults: dict[str, tuple[str, tuple[str, ...]]] = {}
    for target in ScriptTarget:
        if target in (ScriptTarget.ES3, ScriptTarget.ES5):
            file = _ES5_DEFAULT_FILE
        else:
            file = default_files[_TARGET_ALIAS.get(target.value, target.value).upper()]
        defaults[target.value] = (file, _read(file)[1])

    lines = [
        "# Archkeel",
        "# Copyright (c) 2026 Rapiddweller Asia Co., Ltd.",
        "# SPDX-License-Identifier: MIT",
        '"""TypeScript standard-library catalog, generated from the compiler\'s lib files.',
        "",
        f"Generated by tools/typescript_libs.py from typescript {version}; do not edit.",
        '"""',
        "",
        "from enum import StrEnum",
        "from typing import Final",
        "",
        f'TYPESCRIPT_VERSION: Final = "{version}"',
        "",
        "",
        "class StandardLibrary(StrEnum):",
        '    """A `lib` value the pinned compiler accepts; its value is the name it spells."""',
        "",
    ]
    lines += [f'    {_member(name)} = "{name}"' for name in sorted(files)]
    lines += ["", "", "LIB_GLOBALS: Final[dict[StandardLibrary, frozenset[str]]] = {"]
    for name in sorted(catalog):
        names = sorted(catalog[name][0])
        lines.append(f"    StandardLibrary.{_member(name)}: frozenset({{")
        lines += [f'        "{item}",' for item in names]
        lines.append("    }),")
    lines += [
        "}",
        "",
        "LIB_REFERENCES: Final[dict[StandardLibrary, tuple[StandardLibrary, ...]]] = {",
    ]
    for name in sorted(catalog):
        lines.append(f"    StandardLibrary.{_member(name)}: {_literal(catalog[name][1])},")
    lines += [
        "}",
        "",
        "# The references of each target's default lib file, keyed by ScriptTarget value.",
        "DEFAULT_LIBS: Final[dict[str, tuple[StandardLibrary, ...]]] = {",
    ]
    for key, (default_file, default_refs) in sorted(defaults.items()):
        lines.append(f'    "{key}": {_literal(default_refs)},  # {default_file}')
    lines.append("}")
    source = "\n".join(lines) + "\n"
    formatted = subprocess.run(
        [sys.executable, "-m", "ruff", "format", "--stdin-filename", OUTPUT.name, "-"],
        input=source,
        capture_output=True,
        text=True,
        check=True,
        cwd=ROOT,
    )
    return formatted.stdout


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    mode = parser.add_mutually_exclusive_group()
    mode.add_argument("--check", action="store_true", help="fail when the module is stale")
    mode.add_argument("--write", action="store_true", help="regenerate the module (default)")
    args = parser.parse_args(argv)
    module = build_module()
    if args.check:
        if not OUTPUT.is_file() or OUTPUT.read_text(encoding="utf-8") != module:
            print(f"{OUTPUT.relative_to(ROOT)} is stale; run python -m tools.typescript_libs")
            return 1
        return 0
    OUTPUT.write_text(module, encoding="utf-8")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
