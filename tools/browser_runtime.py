"""Verify the Flow derivative and publish the offline Explorer and Studio bundles."""

from __future__ import annotations

import argparse
import json
import shutil
import subprocess
from hashlib import sha256
from pathlib import Path

from archkeel.studio.api import (
    API_VERSION,
    AgentKind,
    ChatBlockKind,
    ChatError,
    ComponentSource,
    ContractState,
    ExploreState,
    SymbolKind,
)

_ROOT = Path(__file__).parents[1]
_ASSETS = _ROOT / "src/archkeel/render/assets"
_SOURCE = _ASSETS / "flow.js"
_OUTPUT = _ASSETS / "flow.runtime.js"
_TOOLS = _ROOT / "tools/browser-runtime"
_COMPILER = _TOOLS / "node_modules/terser/bin/terser"
_OPTIONS = _TOOLS / "options.json"
_BUNDLE = _ASSETS / "explorer.runtime.js"
_STUDIO_UI = _ROOT / "src/archkeel/studio/ui"
_STUDIO = _STUDIO_UI / "studio.js"
_VOCABULARY = _STUDIO_UI / "vocabulary.ts"


def vocabulary_source() -> str:
    """AD-290: the API vocabulary of the UI, from the Python enums of `archkeel.studio.api`."""
    lines = [
        "// Generated by tools/browser_runtime.py from archkeel.studio.api. Do not edit.",
        f"export const API_VERSION = {json.dumps(API_VERSION)};",
    ]
    for domain in (
        AgentKind,
        ChatBlockKind,
        ChatError,
        ComponentSource,
        ContractState,
        ExploreState,
        SymbolKind,
    ):
        name = domain.__name__
        lines.append(f"export const {name} = {{")
        lines.extend(f"  {entry.name}: {json.dumps(entry.value)}," for entry in domain)
        lines.append("} as const;")
        lines.append(f"export type {name} = (typeof {name})[keyof typeof {name}];")
    return "\n".join(lines) + "\n"


def runtime_bytes() -> bytes:
    node = shutil.which("node")
    if node is None:
        raise SystemExit("Flow publication requires Node; installed reports do not.")
    source = _SOURCE.read_bytes()
    result = subprocess.run(
        [node, str(_COMPILER), "--config-file", str(_OPTIONS)],
        input=source,
        capture_output=True,
        check=True,
    )
    provenance = (
        f"// Generated from flow.js; source-sha256={sha256(source).hexdigest()}\n"
        "// Owner: tools/browser_runtime.py. Edit flow.js; make browser-runtime-generate.\n"
    )
    return result.stdout + b"\n" + provenance.encode("utf-8")


def prepare_dependencies() -> None:
    """Expose the genuine locked dependency to the native ancestor-node_modules resolver."""
    package = _TOOLS / "node_modules/elkjs"
    manifest = json.loads((package / "package.json").read_bytes())
    if manifest["name"] != "elkjs" or manifest["version"] != "0.12.0":
        raise SystemExit("ELK package identity differs from the pinned browser dependency")
    canonical = _ASSETS / "elkjs-0.12.0.bundled.js"
    expected = (_ASSETS / "ELKJS-LICENSE.md").read_text(encoding="utf-8").splitlines()[3]
    if expected != f"Bundle SHA-256: `{sha256(canonical.read_bytes()).hexdigest()}`.":
        raise SystemExit("Canonical ELK bytes differ from the recorded license provenance")
    if (package / "lib/elk.bundled.js").read_bytes() != canonical.read_bytes():
        raise SystemExit("Installed ELK differs from the canonical vendored bundle")
    target = _ROOT / "node_modules/elkjs"
    if target.exists():
        expected_files = {
            path.relative_to(package) for path in package.rglob("*") if path.is_file()
        }
        actual_files = {path.relative_to(target) for path in target.rglob("*") if path.is_file()}
        if expected_files != actual_files or any(
            (package / name).read_bytes() != (target / name).read_bytes() for name in expected_files
        ):
            raise SystemExit("Existing root ELK dependency differs; refusing to overwrite it")
        return
    shutil.copytree(package, target)


def bundle_bytes() -> bytes:
    node = shutil.which("node")
    if node is None:
        raise SystemExit("Browser publication requires Node; installed reports do not.")
    published = subprocess.run(
        [node, str(_TOOLS / "bundle.cjs")], capture_output=True, check=True
    ).stdout
    witness = (
        f"// Generated from flow.js; source-sha256={sha256(_SOURCE.read_bytes()).hexdigest()}\n"
    )
    return published + b"\n// Includes the verified Flow derivative.\n" + witness.encode()


def studio_bytes() -> bytes:
    """AD-290: type-check the Studio sources, then bundle them with Preact."""
    node = shutil.which("node")
    if node is None:
        raise SystemExit("Studio publication requires Node; the installed Studio does not.")
    compiler = _TOOLS / "node_modules/typescript/bin/tsc"
    subprocess.run([node, str(compiler), "-p", str(_STUDIO_UI / "tsconfig.json")], check=True)
    return subprocess.run(
        [node, str(_TOOLS / "studio.cjs")], capture_output=True, check=True
    ).stdout


def check() -> None:
    if _VOCABULARY.read_text(encoding="utf-8") != vocabulary_source():
        raise SystemExit("Studio vocabulary is stale; run make browser-runtime-generate.")
    if _OUTPUT.read_bytes() != runtime_bytes():
        raise SystemExit("Flow runtime is stale; run make browser-runtime-generate.")
    if _BUNDLE.read_bytes() != bundle_bytes():
        raise SystemExit("Explorer bundle is stale; run make browser-runtime-generate.")
    if _STUDIO.read_bytes() != studio_bytes():
        raise SystemExit("Studio bundle is stale; run make browser-runtime-generate.")


def generate() -> None:
    _OUTPUT.write_bytes(runtime_bytes())
    _BUNDLE.write_bytes(bundle_bytes())
    _VOCABULARY.write_text(vocabulary_source(), encoding="utf-8")
    _STUDIO.write_bytes(studio_bytes())


class _Arguments(argparse.Namespace):
    check: bool = False
    prepare_dependencies: bool = False


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    parser.add_argument("--prepare-dependencies", action="store_true")
    arguments = parser.parse_args(namespace=_Arguments())
    if arguments.prepare_dependencies:
        prepare_dependencies()
    elif arguments.check:
        check()
    else:
        generate()


if __name__ == "__main__":
    main()
