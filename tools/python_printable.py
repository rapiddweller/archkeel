"""Generate the table of the characters that Python `repr` escapes, for the Rust store (AD-346).

The receipt digest of a dependency proof hashes the Python `repr` of whole records. The Rust store
writes the same text, so it needs the code points above U+007F that `str.isprintable` rejects.
The set depends on the Unicode version of the interpreter. `--check` fails when the checked-in
table differs from the table of the running interpreter; `--write` (the default) writes it.
"""

from __future__ import annotations

import argparse
import sys
import unicodedata
from pathlib import Path
from typing import Final

ROOT: Final = Path(__file__).resolve().parents[1]
OUTPUT: Final = ROOT / "native/store/src/printable.rs"
_PER_LINE: Final = 8


def ranges() -> list[tuple[int, int]]:
    """The inclusive ranges of the code points from U+0080 that `str.isprintable` rejects."""
    result: list[tuple[int, int]] = []
    start: int | None = None
    for point in range(0x80, sys.maxunicode + 2):
        hidden = point <= sys.maxunicode and not chr(point).isprintable()
        if hidden and start is None:
            start = point
        elif not hidden and start is not None:
            result.append((start, point - 1))
            start = None
    return result


def source() -> str:
    pairs = [f"{low:05X}-{high:05X}" for low, high in ranges()]
    lines = [" ".join(pairs[i : i + _PER_LINE]) for i in range(0, len(pairs), _PER_LINE)]
    body = " \\\n".join(lines)
    return (
        "// Archkeel\n"
        "// Copyright (c) 2026 Rapiddweller Asia Co., Ltd.\n"
        "// SPDX-License-Identifier: MIT\n\n"
        "//! Generated by `tools/python_printable.py`. Do not edit.\n"
        "//!\n"
        f"//! The code points from U+0080 that Python `repr` escapes (Unicode "
        f"{unicodedata.unidata_version}).\n\n"
        "/// The Unicode version of the table; the Python shell test compares it with its own.\n"
        "#[cfg(test)]\n"
        f'pub(crate) const UNICODE_VERSION: &str = "{unicodedata.unidata_version}";\n\n'
        "/// Sorted, inclusive and disjoint ranges in hexadecimal: `low-high`, separated by spaces.\n"
        "#[rustfmt::skip]\n"
        'pub(crate) const HIDDEN: &str = "\\\n'
        f"{body}\";\n"
    )


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    arguments = parser.parse_args(argv)
    text = source()
    if arguments.check:
        if OUTPUT.read_text(encoding="utf-8") != text:
            print(f"{OUTPUT.relative_to(ROOT)} differs: run tools/python_printable.py")
            return 1
        return 0
    OUTPUT.write_text(text, encoding="utf-8")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
