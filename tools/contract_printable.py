"""Write the table of characters that Python `repr` escapes, for the Rust contract crate (L-28).

Python `repr` escapes each character for which `str.isprintable()` is false. The table is the
ranges of those code points under Python 3.11 (Unicode 14). Run it with Python 3.11:

    python3.11 tools/contract_printable.py            # write the table
    python3.11 tools/contract_printable.py --check    # exit 1 when the table differs
"""

from __future__ import annotations

import argparse
import sys
import unicodedata
from pathlib import Path

TABLE = Path(__file__).parents[1] / "native/contract/src/policy/printable.rs"
HEADER = """// Archkeel
// Copyright (c) 2026 Rapiddweller Asia Co., Ltd.
// SPDX-License-Identifier: MIT

//! Generated by `tools/contract_printable.py` from Python 3.11 (Unicode {unicode}); do not edit.
//! The ranges of code points for which `str.isprintable()` is false: Python `repr` escapes them
//! (L-28).

/// The inclusive ranges of the code points that Python `repr` escapes, in order.
#[rustfmt::skip]
pub(crate) const NOT_PRINTABLE: &[(u32, u32)] = &[
"""


def ranges() -> list[tuple[int, int]]:
    found: list[tuple[int, int]] = []
    for code in range(sys.maxunicode + 1):
        if chr(code).isprintable():
            continue
        if found and found[-1][1] == code - 1:
            found[-1] = (found[-1][0], code)
        else:
            found.append((code, code))
    return found


def table() -> str:
    items = [f"(0x{start:X}, 0x{end:X})," for start, end in ranges()]
    lines = ["    " + " ".join(items[index : index + 4]) for index in range(0, len(items), 4)]
    return HEADER.format(unicode=unicodedata.unidata_version) + "\n".join(lines) + "\n];\n"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    arguments = parser.parse_args()
    if sys.version_info[:2] != (3, 11):
        print("run this tool with Python 3.11: the table is the Unicode 14 of Python 3.11")
        return 2
    text = table()
    if arguments.check:
        return 0 if TABLE.read_text(encoding="utf-8") == text else 1
    TABLE.write_text(text, encoding="utf-8")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
