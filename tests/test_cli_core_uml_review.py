def entity(identity: str, name: str, language: str, kind: str = "module", **extra: Any) -> dict:
    planned = extra.get("presence", "planned") == "planned"
    return {
        "id": identity,
        "kind": kind,
        "qualified_name": name,
        "language": language,
        "presence": "planned",
        "provenance": PROVENANCE,
        **({"responsibilities": ["Hold it."]} if planned else {}),
        **extra,
    }


def imports(source: str, target: str) -> dict:
    return {
        "id": f"{source}-{target}",
        "kind": "imports",
        "source_id": source,
        "target_id": target,
        "provenance": PROVENANCE,
    }


def scope(identity: str, relationships: list[str], mode: str = "closed") -> dict:
    return {
        "scope_id": identity,
        "mode": mode,
        "rationale": "Keep it.",
        "provenance": PROVENANCE,
        "entity_kinds": [],
        "relationship_kinds": relationships,
    }


def uml(entities: list[dict], relationships: list[dict], scopes: list[dict] = ()) -> dict:
    return {
        "schema_version": "1.1.0",
        "entities": entities,
        "relationships": relationships,
        "scopes": list(scopes),
    }


def component(name: str, packages: list[str], requires: tuple[str, ...] = ()) -> dict:
    return {
        "id": name.upper(),
        "label": name,
        "role": "component",
        "packages": packages,
        "responsibilities": ["Own."],
        "forbidden_responsibilities": [],
        "provenance": PROVENANCE,
        "decided_by": "architect",
        "requires": [{"component": other, "rationale": "Use it."} for other in requires],
    }


def readme(edge: bool, nodes: int = 2) -> str:
    names = "".join(f'    n_{index}["{"ab"[index]}"]\n' for index in range(nodes))
    return (
        "# Provenance\n\n<!-- archkeel-component-graph -->\n```mermaid\nflowchart LR\n"
        f"{names}{'    n_0 --> n_1' + chr(10) if edge else ''}```\n"
    )


def two(prefix: str) -> list[dict]:
    return [component("a", [f"{prefix}.a"], ("b",)), component("b", [f"{prefix}.b"])]


