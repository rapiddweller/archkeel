def project(root: Path, plant: tuple) -> Path:
    configuration, files, components, target = plant
    rust = configuration == RUST
    # AD-466: the provenance file draws the component graph of the imports of component a.
    sources = [text for path, text in files.items() if "/a/" in path]
    edge = any(mark in text for text in sources for mark in ("../b/t", "app.b.t"))
    written = {"README.md": readme(edge and not rust, 1 if rust else 2), **files}
    for name, text in written.items():
        (root / name).parent.mkdir(parents=True, exist_ok=True)
        (root / name).write_text(text)
    (root / "archkeel.toml").write_text(configuration)
    contract = {
        "schema_version": "2.2.0",
        "components": components,
        "rules": [] if rust else RULE,
        "declarations": {"uml": target},
    }
    (root / "architecture-contract.json").write_text(json.dumps(contract))
    env = {
        **os.environ,
        "GIT_AUTHOR_NAME": "t",
        "GIT_AUTHOR_EMAIL": "t@t",
        "GIT_COMMITTER_NAME": "t",
        "GIT_COMMITTER_EMAIL": "t@t",
    }
    for step in (["init", "-q"], ["add", "-A"], ["commit", "-qm", "init"]):
        subprocess.run(["git", "-C", str(root), *step], check=True, env=env)
    return root


@pytest.mark.parametrize("name", sorted(PLANTS))
def test_the_review_forms_give_the_release_row_or_a_stricter_or_ruled_row(
    release_core: Path, tmp_path: Path, name: str
) -> None:
    plant, _, expected = PLANTS[name]
    done = command(release_core, project(tmp_path, plant), "--json")
    result = json.loads(done.stdout)
    assert "refusal" not in result, result
    frame = result["frame"]
    assert frame["rules"][ROW] == ["uml_target", expected], frame.get("explained")
    if expected == "FAIL":
        assert frame["details"][ROW], frame


@pytest.mark.parametrize(
    "target",
    [
        uml(
            [*TS_MODULES, entity("p", "app.src.a", "typescript", "component")],
            [],
            [scope("p", ["imports"], "open")],
        ),
        uml(
            [
                entity("p", "app.src.a", "typescript", "component"),
                entity("one", ONE, "typescript", parent_id="p"),
            ],
            [],
        ),
    ],
    ids=["component-scope", "component-parent"],
)
def test_a_component_entity_in_the_target_refuses_the_contract(
    release_core: Path, tmp_path: Path, target: dict
) -> None:
    """B3: 4.0.1 refuses the contract: "UML cannot redeclare an existing component owner"."""
    done = command(
        release_core, project(tmp_path, (TS, TS_FILES, two("app.src"), target)), "--json"
    )
    result = json.loads(done.stdout)
    refusal = json.dumps(result["frame"]["unsupported"])
    assert "UML cannot redeclare an existing component owner" in refusal, result["frame"]
    assert done.returncode == 2
