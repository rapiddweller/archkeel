"""The Markdown guide renders the core topology and pins its bytes (AD-1121)."""

from __future__ import annotations

from dataclasses import replace

from archkeel.cli import core_arguments
from archkeel.cli.core_guide import render
from archkeel.cli.core_topology import Component, LayerOrder, Require, Topology

APP = Component(
    id="COMP-APP",
    name="app",
    parent=None,
    packages=("app",),
    exact_modules=(),
    planned=False,
    layer="application",
    public=("app.api:Api",),
    responsibilities=("Serves requests.",),
    forbidden_responsibilities=("Reading files.",),
    planned_public=(),
)
BASE = Component(
    id="COMP-BASE",
    name="base",
    parent=None,
    packages=("base", "base.types"),
    exact_modules=(),
    planned=True,
    layer=None,
    public=(),
    responsibilities=(),
    forbidden_responsibilities=(),
    planned_public=("base:Type",),
)
REQUIRE = Require(
    source="COMP-APP",
    target="COMP-BASE",
    imports=3,
    rationale="The app uses the base types.",
    through=(),
)
LAYER = LayerOrder(rule="LAYER-ORDER", layers=("base", "application"))
TOTAL = {
    "components": 2,
    "modules": 0,
    "edges": 0,
    "component_edges": 0,
    "requires": 1,
    "layers": 1,
}
COMPLETE = Topology(
    complete=True,
    truncated=False,
    gaps=(),
    total=TOTAL,
    components=(APP, BASE),
    modules=(),
    edges=(),
    component_edges=(),
    requires=(REQUIRE,),
    layers=(LAYER,),
)

PINNED = """\
# Architecture guide

Generated by `archkeel report --format markdown`. It shows declared facts, not verdicts.

The core lists every component and requirement of the contract.

## Components

### app (`COMP-APP`)

- Status: declared
- Layer: application
- Parent: none

Packages:

- `app`

Responsibilities:

- Serves requests.

Must not:

- Reading files.

Public interfaces:

- `app.api:Api`

### base (`COMP-BASE`)

- Status: planned
- Layer: not set
- Parent: none

Packages:

- `base`
- `base.types`

Responsibilities:

None declared.

Must not:

None declared.

Public interfaces:

None declared.

Planned public interfaces:

- `base:Type`

## Requirements

- `COMP-APP` requires `COMP-BASE`: The app uses the base types. (3 observed imports)

## Layer orders

Each order runs from the inner layer to the outer layer.

- `LAYER-ORDER`: base -> application
"""


def test_render_pins_the_markdown_of_a_complete_topology() -> None:
    assert render(COMPLETE) == PINNED


def test_render_states_an_incomplete_topology_and_its_gaps() -> None:
    partial = replace(
        COMPLETE,
        complete=False,
        gaps=("modules",),
        total={**TOTAL, "components": 3},
    )
    text = render(partial)
    assert text.startswith(
        "# Architecture guide\n\n"
        "Generated by `archkeel report --format markdown`. "
        "It shows declared facts, not verdicts.\n\n"
        "The core marks this topology as incomplete. Read the gaps before you rely on it.\n\n"
        "- Gap: modules\n"
        "- Listed: 2 of 3 components; 1 of 1 requirements.\n"
    )


def test_render_is_deterministic() -> None:
    assert render(COMPLETE) == render(COMPLETE)


def test_format_markdown_turns_on_the_topology_section() -> None:
    options = core_arguments.parse(["report", "--output", "guide.md", "--format", "markdown"])
    assert options.format == "markdown"
    assert options.topology is True
