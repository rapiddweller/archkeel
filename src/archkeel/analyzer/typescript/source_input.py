"""Decode TypeScript filenames and specifiers; arbitrary path and module names remain data."""

from __future__ import annotations

import posixpath
import re
from dataclasses import dataclass
from enum import Enum, StrEnum
from typing import Final


class PathToken(Enum):
    """Closed path/glob grammar, distinct from user-supplied path names."""

    CURRENT = "."
    PARENT = ".."
    ROOT = "/"
    RELATIVE = "./"
    STAR = "*"
    DEEP_STAR = "**"
    QUESTION = "?"
    NODE_MODULES = "node_modules"

    @staticmethod
    def parse(value: str) -> PathToken | None:
        return _PATH_TOKENS.get(value)


class ModuleFormat(Enum):
    """The loading format passed between resolution and collection."""

    ESM = "esm"
    CJS = "cjs"


class SourceKind(Enum):
    """The source categories enabled for one resolution pass."""

    TYPESCRIPT = "ts"
    DECLARATION = "dts"
    JAVASCRIPT = "js"
    JSON = "json"


class FileSuffix(StrEnum):
    NONE = ""
    DTS = ".d.ts"
    DMTS = ".d.mts"
    DCTS = ".d.cts"
    MJS = ".mjs"
    MTS = ".mts"
    CJS = ".cjs"
    CTS = ".cts"
    TS = ".ts"
    JS = ".js"
    TSX = ".tsx"
    JSX = ".jsx"
    JSON = ".json"
    # Generated by JSON substitution; input recognition still sees its existing .ts suffix.
    JSON_DECLARATION = ".d.json.ts"

    @property
    def source_kind(self) -> SourceKind | None:
        return _FILE_RULES[self].kind

    @property
    def format_hint(self) -> ModuleFormat | None:
        return _FILE_RULES[self].format

    @property
    def scoped_format(self) -> bool:
        return self.source_kind is not None and self.format_hint is None

    @property
    def parser_typescript(self) -> bool:
        return (
            self.source_kind in (SourceKind.TYPESCRIPT, SourceKind.DECLARATION)
            and self is not FileSuffix.TSX
        )

    @property
    def explicit_runtime(self) -> bool:
        return self in (FileSuffix.JS, FileSuffix.MJS, FileSuffix.CJS)

    @property
    def priority(self) -> tuple[FileSuffix, ...]:
        return _FILE_RULES[self].priority

    def replacements(self, kinds: tuple[SourceKind, ...]) -> list[FileSuffix]:
        return [
            suffix
            for suffix in _FILE_RULES[self].family
            if (SourceKind.JSON if suffix is FileSuffix.JSON else suffix.source_kind) in kinds
        ]


@dataclass(frozen=True, slots=True)
class FileParts:
    stem: str
    suffix: FileSuffix


@dataclass(frozen=True, slots=True)
class _FileRule:
    kind: SourceKind | None
    format: ModuleFormat | None = None
    family: tuple[FileSuffix, ...] = ()
    priority: tuple[FileSuffix, ...] = ()


_PLAIN: Final = (FileSuffix.TS, FileSuffix.TSX, FileSuffix.DTS, FileSuffix.JS, FileSuffix.JSX)
_ESM: Final = (FileSuffix.MTS, FileSuffix.DMTS, FileSuffix.MJS)
_CJS: Final = (FileSuffix.CTS, FileSuffix.DCTS, FileSuffix.CJS)
_JSX: Final = (FileSuffix.TSX, FileSuffix.TS, FileSuffix.DTS, FileSuffix.JSX, FileSuffix.JS)
_FILE_RULES: Final[dict[FileSuffix, _FileRule]] = {
    FileSuffix.NONE: _FileRule(None, family=_PLAIN),
    FileSuffix.DTS: _FileRule(SourceKind.DECLARATION, family=_PLAIN, priority=_PLAIN),
    FileSuffix.DMTS: _FileRule(SourceKind.DECLARATION, ModuleFormat.ESM, _ESM, _ESM),
    FileSuffix.DCTS: _FileRule(SourceKind.DECLARATION, ModuleFormat.CJS, _CJS, _CJS),
    FileSuffix.MJS: _FileRule(SourceKind.JAVASCRIPT, ModuleFormat.ESM, _ESM, _ESM),
    FileSuffix.MTS: _FileRule(SourceKind.TYPESCRIPT, ModuleFormat.ESM, _ESM, _ESM),
    FileSuffix.CJS: _FileRule(SourceKind.JAVASCRIPT, ModuleFormat.CJS, _CJS, _CJS),
    FileSuffix.CTS: _FileRule(SourceKind.TYPESCRIPT, ModuleFormat.CJS, _CJS, _CJS),
    FileSuffix.TS: _FileRule(SourceKind.TYPESCRIPT, family=_PLAIN, priority=_PLAIN),
    FileSuffix.JS: _FileRule(SourceKind.JAVASCRIPT, family=_PLAIN, priority=_PLAIN),
    FileSuffix.TSX: _FileRule(SourceKind.TYPESCRIPT, family=_JSX, priority=_PLAIN),
    FileSuffix.JSX: _FileRule(SourceKind.JAVASCRIPT, family=_JSX, priority=_PLAIN),
    FileSuffix.JSON: _FileRule(None, family=(FileSuffix.JSON_DECLARATION, FileSuffix.JSON)),
    FileSuffix.JSON_DECLARATION: _FileRule(SourceKind.DECLARATION),
}
# Longest recognized input suffix wins, including declarations and dotfiles.
_SUFFIX: Final[re.Pattern[str]] = re.compile(
    "(?:"
    + "|".join(
        re.escape(suffix)
        for suffix in sorted(FileSuffix, key=len, reverse=True)
        if suffix not in (FileSuffix.NONE, FileSuffix.JSON_DECLARATION)
    )
    + r")\Z"
)
_PATH_TOKENS: Final[dict[str, PathToken]] = {member.value: member for member in PathToken}


def classify_file(name: str) -> FileSuffix | None:
    """Known suffix, explicit absence, or None for an unsupported suffix."""
    found = _SUFFIX.search(name)
    if found is not None:
        return FileSuffix(found[0])
    return FileSuffix.NONE if re.search(r"\.", posixpath.basename(name)) is None else None


def split_file(name: str) -> FileParts | None:
    """Split only recognized input suffixes; unsupported names never gain a known family."""
    suffix = classify_file(name)
    if suffix is None or suffix is FileSuffix.NONE:
        return None
    return FileParts(name[: -len(suffix)], suffix)


class SpecifierKind(Enum):
    CURRENT = "current"
    PARENT = "parent"
    CURRENT_PATH = "current_path"
    PARENT_PATH = "parent_path"
    ABSOLUTE = "absolute"
    NODE = "node"
    SCOPED = "scoped"
    IMPORTS = "imports"
    BARE = "bare"


@dataclass(frozen=True, slots=True)
class SpecifierInfo:
    original: str
    kind: SpecifierKind
    name: str
    package: str
    typed_name: str
    directory_only: bool

    @property
    def relative_path(self) -> bool:
        return self.kind in (SpecifierKind.CURRENT_PATH, SpecifierKind.PARENT_PATH)

    @property
    def relative(self) -> bool:
        return self.relative_path or self.kind in (SpecifierKind.CURRENT, SpecifierKind.PARENT)

    @property
    def builtin(self) -> bool:
        return self.name in _BUILTINS or (
            self.kind is SpecifierKind.NODE and self.name in _SCHEME_ONLY
        )


_SPECIFIER: Final[re.Pattern[str]] = re.compile(
    r"(?P<current>\.\Z)|(?P<parent>\.\.\Z)|(?P<current_path>\./)|"
    r"(?P<parent_path>\.\./)|(?P<absolute>/)|(?P<node>node:)|(?P<scoped>@)|(?P<imports>\#)"
)
# `module.builtinModules` of Node 22, plus the names that exist only with the `node:` prefix.
_BUILTINS: Final = frozenset(
    "_http_agent _http_client _http_common _http_incoming _http_outgoing _http_server "
    "_stream_duplex _stream_passthrough _stream_readable _stream_transform _stream_wrap "
    "_stream_writable _tls_common _tls_wrap assert assert/strict async_hooks buffer "
    "child_process cluster console constants crypto dgram diagnostics_channel dns "
    "dns/promises domain events fs fs/promises http http2 https inspector inspector/promises "
    "module net os path path/posix path/win32 perf_hooks process punycode querystring readline "
    "readline/promises repl stream stream/consumers stream/promises stream/web string_decoder "
    "sys timers timers/promises tls trace_events tty url util util/types v8 vm wasi "
    "worker_threads zlib".split()
)
_SCHEME_ONLY: Final = frozenset({"sea", "sqlite", "test", "test/reporters"})


def classify_specifier(text: str) -> SpecifierInfo:
    """Classify reserved syntax once; all remaining module-name text is open input data."""
    found = _SPECIFIER.match(text)
    kind = SpecifierKind(found.lastgroup) if found is not None else SpecifierKind.BARE
    name = text[found.end() :] if kind is SpecifierKind.NODE and found is not None else text
    parts = text.split("/")
    package = "/".join(parts[:2]) if kind is SpecifierKind.SCOPED else parts[0]
    typed_name = (
        text.replace("/", "__", 1)[1:]
        if kind is SpecifierKind.SCOPED and len(parts) > 1
        else text
    )
    return SpecifierInfo(
        original=text,
        kind=kind,
        name=name,
        package=package,
        typed_name=typed_name,
        directory_only=PathToken.parse(text[-1:]) is PathToken.ROOT,
    )
